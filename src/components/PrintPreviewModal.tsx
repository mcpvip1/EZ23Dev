export interface PrintPreviewRow {
  personNo: string;
  betDay: string;
  session: 'AM' | 'PM';
  betDateTime: string;
  amount: number;
  winNo: string;
  winAmt: number;
  com: number;
  rate: number;
  netAmount: number;
}

export interface PrintPreviewProps {
  reportTitle: string;
  reportSubtitle: string;
  betDay: string;
  session: 'AM' | 'PM';
  luckyNo: string | null;
  kpis: {
    totalAmount: number;
    totalWin: number;
    totalNet: number;
    totalRows: number;
    uniquePersons: number;
  };
  fighterRows: PrintPreviewRow[];
  ownerRows: PrintPreviewRow[];
  onClose: () => void;
}

/**
 * Generates a clean, mobile/WhatsApp-friendly plain-text settlement report
 * suitable for the Web Share API (`navigator.share`), WhatsApp, Telegram, or Viber.
 */
export function buildShareableReportText(p: PrintPreviewProps): string {
  const lines: string[] = [];
  lines.push(`*${p.reportTitle} — ငွေစာရင်း အခြေချရှင်းတမ်း*`);
  lines.push(`📅 ရက်စွဲ: ${p.betDay} (${p.session})`);
  lines.push(`🎯 ထွက်ဂဏန်း: ${p.luckyNo ? p.luckyNo : 'မထွက်သေးပါ'}`);
  lines.push(`📌 အပိုင်းအခြား: ${p.reportSubtitle}`);
  lines.push(`────────────────────`);
  lines.push(`📊 *အကျဉ်းချုပ် (Summary)*`);
  lines.push(`• စုစုပေါင်း ပမာဏ: ${fmt(p.kpis.totalAmount)} Ks`);
  lines.push(`• ပေါက်ငွေ စုစုပေါင်း: ${fmt(p.kpis.totalWin)} Ks`);
  const netStr = p.kpis.totalNet < 0 ? `(-)${fmt(Math.abs(p.kpis.totalNet))}` : fmt(p.kpis.totalNet);
  lines.push(`• အသားတင် (${p.kpis.totalNet >= 0 ? 'အမြတ်' : 'အရှုံး'}): *${netStr} Ks*`);
  lines.push(`• ပါဝင်သူ ဦးရေ: ${p.kpis.uniquePersons} ဦး (${p.kpis.totalRows} ကြိမ်)`);

  const appendSection = (heading: string, rows: PrintPreviewRow[]) => {
    if (rows.length === 0) return;
    lines.push(`────────────────────`);
    lines.push(`*${heading}*`);
    let totAmt = 0;
    let totWin = 0;
    let totNet = 0;
    rows.forEach((r, idx) => {
      totAmt += r.amount;
      totWin += r.winAmt;
      totNet += r.netAmount;
      const netFormatted = r.netAmount < 0 ? `(-)${fmt(Math.abs(r.netAmount))}` : fmt(r.netAmount);
      const winPart = r.winAmt > 0 ? ` | ပေါက်(${r.winNo})=${fmt(r.winAmt)}` : '';
      lines.push(
        `${idx + 1}. #${r.personNo} [${r.betDay} ${r.session}] T=${fmt(r.amount)}${winPart} (${r.com}%/${r.rate}) => *You=${netFormatted}*`,
      );
    });
    const subNetStr = totNet < 0 ? `(-)${fmt(Math.abs(totNet))}` : fmt(totNet);
    lines.push(`Σ စုစုပေါင်း: T=${fmt(totAmt)} | P=${fmt(totWin)} | *Net=${subNetStr} Ks*`);
  };

  appendSection('ဖိုက်တာ — ထိုးငွေ (Fighter Bets)', p.fighterRows);
  appendSection('ဒိုင် — ပို့ငွေ (Owner Carry)', p.ownerRows);

  lines.push(`────────────────────`);
  lines.push(`✍️ စာရင်းကိုင်: ______________`);
  lines.push(`✍️ ဒိုင်/မန်နေဂျာ: ______________`);
  lines.push(`_Generated by EASY 2D Pro_`);
  return lines.join('\n');
}

async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const ta = document.createElement('textarea');
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      ta.remove();
      return true;
    } catch {
      return false;
    }
  }
}

